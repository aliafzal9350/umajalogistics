import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../lib/pallet-fit.js', import.meta.url), 'utf8');
const { palletFit } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const example = { length: 312, width: 95, palletLength: 48, palletWidth: 40, count: 12, weight: 500, payload: '', palletHeight: '', doorHeight: '' };
assert.equal(palletFit(example).capacity, 12);
assert.equal(palletFit(example).totalWeight, 6000);
assert.equal(palletFit(example).payloadFits, null);
assert.equal(palletFit(example).heightFits, null);
assert.equal(palletFit({ ...example, count: 13 }).floorFits, false);
assert.equal(palletFit({ ...example, payload: 5000 }).payloadFits, false);
assert.equal(palletFit({ ...example, payload: 6000 }).payloadFits, true);
assert.equal(palletFit({ ...example, palletHeight: 96, doorHeight: 90 }).heightFits, false);
assert.equal(palletFit({ ...example, palletHeight: 80, doorHeight: 90 }).heightFits, true);
const rotated = palletFit({ ...example, length: 120, width: 100, palletLength: 40, palletWidth: 60 });
assert.equal(rotated.capacity, 4);
assert.equal(rotated.rotated, true);
assert.equal(palletFit({ ...example, palletWidth: 500, palletLength: 500 }).capacity, 0);
for (const values of [{ width: 0 }, { length: '' }, { count: 1.5 }, { weight: -1 }, { payload: -1 }, { doorHeight: 'abc' }, { length: Infinity }]) assert(palletFit({ ...example, ...values }).error);
console.log('PASS: pallet layouts, rotation, payload, door clearance and invalid inputs');
